'use strict';

const fs = require('fs');
const path = require('path');
const { ensureAudioFixtures } = require('./fixtures');

// --- byte helpers -----------------------------------------------------------
function u32le(n) {
  const b = Buffer.alloc(4);
  b.writeUInt32LE(n >>> 0);
  return b;
}
function synchsafe(n) {
  return Buffer.from([(n >> 21) & 0x7f, (n >> 14) & 0x7f, (n >> 7) & 0x7f, n & 0x7f]);
}

// --- ID3v2.4 ----------------------------------------------------------------
function frame(id, payload) {
  return Buffer.concat([Buffer.from(id, 'latin1'), synchsafe(payload.length), Buffer.from([0, 0]), payload]);
}
function textFrame(id, text) {
  return frame(id, Buffer.concat([Buffer.from([0x03]), Buffer.from(text, 'utf8')]));
}
function txxxFrame(desc, value) {
  return frame('TXXX', Buffer.concat([Buffer.from([0x03]), Buffer.from(desc, 'utf8'), Buffer.from([0]), Buffer.from(value, 'utf8')]));
}
function privFrame(owner, data) {
  return frame('PRIV', Buffer.concat([Buffer.from(owner, 'latin1'), Buffer.from([0]), Buffer.from(data)]));
}
function id3Tag(frames) {
  const body = Buffer.concat(frames);
  return Buffer.concat([Buffer.from('ID3'), Buffer.from([0x04, 0x00, 0x00]), synchsafe(body.length), body]);
}

// --- RIFF / WAV -------------------------------------------------------------
function chunk(fourCC, payload) {
  const parts = [Buffer.from(fourCC, 'latin1'), u32le(payload.length), payload];
  if (payload.length % 2) parts.push(Buffer.from([0])); // word alignment
  return Buffer.concat(parts);
}
function fmtChunk() {
  const p = Buffer.alloc(16);
  p.writeUInt16LE(1, 0); // PCM
  p.writeUInt16LE(1, 2); // mono
  p.writeUInt32LE(8000, 4);
  p.writeUInt32LE(16000, 8);
  p.writeUInt16LE(2, 12);
  p.writeUInt16LE(16, 14);
  return chunk('fmt ', p);
}
function listInfoChunk(entries) {
  const subs = entries.map((e) => chunk(e.id, Buffer.from(e.val + '\0', 'latin1')));
  return chunk('LIST', Buffer.concat([Buffer.from('INFO'), ...subs]));
}
function bextChunk(fields) {
  const p = Buffer.alloc(602);
  p.write((fields.description || '').slice(0, 255), 0, 'latin1');
  p.write((fields.originator || '').slice(0, 31), 256, 'latin1');
  p.write((fields.originatorReference || '').slice(0, 31), 288, 'latin1');
  p.write((fields.originationDate || '').slice(0, 10), 320, 'latin1');
  p.write((fields.originationTime || '').slice(0, 8), 330, 'latin1');
  return chunk('bext', p);
}
function ixmlChunk(xml) {
  return chunk('iXML', Buffer.from(xml, 'utf8'));
}
function assembleWav(extra = []) {
  const chunks = [fmtChunk(), chunk('data', Buffer.alloc(32)), ...extra];
  const body = Buffer.concat([Buffer.from('WAVE'), ...chunks]);
  return Buffer.concat([Buffer.from('RIFF'), u32le(body.length), body]);
}

// --- fixture writer ---------------------------------------------------------
function makeAuditFixtures(dir) {
  fs.mkdirSync(dir, { recursive: true });
  const { mp3: realMp3 } = ensureAudioFixtures();
  const mp3Body = fs.readFileSync(realMp3);
  const out = {};

  const w = (name, buf) => {
    const p = path.join(dir, name);
    fs.writeFileSync(p, buf);
    return p;
  };

  // MP3 with ID3v2.4: TIT2, TPE1, TXXX(generated by Suno), PRIV(binary), TENC.
  out.mp3Rich = w(
    'rich.mp3',
    Buffer.concat([
      id3Tag([
        textFrame('TIT2', 'Sunlight Through the Window'),
        textFrame('TPE1', 'Test Artist'),
        textFrame('TENC', 'Suno'),
        txxxFrame('provenance', 'generated by Suno'),
        privFrame('com.suno.id', Buffer.from([0x00, 0x11, 0x22, 0x33, 0x44])),
      ]),
      mp3Body,
    ])
  );

  // Clean WAV (no metadata chunks).
  out.wavClean = w('clean.wav', assembleWav());
  // WAV + LIST/INFO (ISFT=Suno maps to ffprobe "encoder").
  out.wavInfo = w('info.wav', assembleWav([listInfoChunk([{ id: 'ISFT', val: 'Suno' }, { id: 'INAM', val: 'Sunlight' }])]));
  // WAV + bext.
  out.wavBext = w('bext.wav', assembleWav([bextChunk({ description: 'origin test', originator: 'Suno', originationDate: '2026-08-11' })]));
  // WAV + iXML.
  out.wavIxml = w('ixml.wav', assembleWav([ixmlChunk('<?xml version="1.0"?><BWFXML><PROJECT>Suno</PROJECT></BWFXML>')]));
  // WAV + unknown chunk.
  out.wavUnknown = w('unknown.wav', assembleWav([chunk('XyZq', Buffer.from('mysterious'))]));

  // Raw binaries (not audio) for the string scanner. NUL padding isolates each
  // printable run so hits carry a meaningful offset.
  out.binSuno = w('suno.bin', Buffer.concat([Buffer.alloc(1000, 0x00), Buffer.from('https://cdn1.suno.ai/track.mp3'), Buffer.alloc(500, 0x00)]));
  out.binSunoOffset = 1000;
  out.binAiCoincidence = w('ai.bin', Buffer.concat([Buffer.alloc(64, 0x00), Buffer.from('note AI here'), Buffer.alloc(64, 0x00)]));
  out.binLicenseNC = w('license.bin', Buffer.from('This work is licensed for non-commercial personal use only.'));
  out.binLicenseConflict = w('conflict.bin', Buffer.from('Free for commercial use. Also marked non-commercial in places.'));
  out.binSecret = w('secret.bin', Buffer.from('audio at https://cdn1.suno.ai/x.mp3?token=SECRET123&Signature=ABCXYZ end'));

  return out;
}

module.exports = {
  makeAuditFixtures,
  id3Tag,
  textFrame,
  txxxFrame,
  privFrame,
  assembleWav,
  listInfoChunk,
  bextChunk,
  ixmlChunk,
  chunk,
};
